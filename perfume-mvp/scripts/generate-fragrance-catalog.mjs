function detectBrand(name) {
  for (const brand of BRANDS) {
    if (name.startsWith(brand + ' ') || name === brand) return brand;
  }
  return name.split(' ')[0];
}

function toSlug(name) {
  return name
    .toLowerCase()
    .replace(/['']/g, '')        // remove apostrophes: Bade'e → Badee
    .replace(/&/g, ' ')          // & → space: Viktor&Rolf → Viktor Rolf
    .replace(/[^a-z0-9]+/g, '-') // non-alphanumeric runs → hyphen
    .replace(/^-|-$/g, '');      // trim leading/trailing hyphens
}

const raw = readFileSync(listPath, 'utf-8');
const lines = raw.split('\n').map((l) => l.trim()).filter(Boolean);

const entries = [];
for (const line of lines) {
  // Header lines like "Afnan (5)" don't contain " — "
  if (!line.includes(' — ')) continue;

  const sepIdx = line.indexOf(' — ');
  const name = line.slice(0, sepIdx).trim();
  const meta = line.slice(sepIdx + 3).trim();

  // Skip header lines that don't describe a perfume (real entries always contain "in Bangladesh")
  if (!meta.includes('in Bangladesh')) continue;

  const brand = detectBrand(name);
  const slug = toSlug(name);

  // Alias is the text before " in Bangladesh" in the meta description
  const inBdIdx = meta.indexOf(' in Bangladesh');
  const alias = inBdIdx > -1 ? meta.slice(0, inBdIdx).trim() : name;

  // Only include alias in searchTerms if it differs from the full name
  const searchTerms = alias !== name ? [name, alias] : [name];

  entries.push({ slug, name, brand, metaDescription: meta, searchTerms });
}

const lines_out = [
  '// AUTO-GENERATED by scripts/generate-fragrance-catalog.mjs — do not edit by hand.',
  '// To add a new perfume, add an entry to list.txt and re-run scripts/generate-fragrance-catalog.mjs.',
  '',
  'export interface PerfumeCatalogEntry {',
  '  slug: string;',
  '  name: string;',
  '  brand: string;',
  '  metaDescription: string;',
  '  searchTerms: string[];',
  '}',
  '',
  'export const fragranceCatalog: PerfumeCatalogEntry[] = [',
  ...entries.map((e) =>
    [
      '  {',
      `    slug: ${JSON.stringify(e.slug)},`,
      `    name: ${JSON.stringify(e.name)},`,
      `    brand: ${JSON.stringify(e.brand)},`,
      `    metaDescription: ${JSON.stringify(e.metaDescription)},`,
      `    searchTerms: ${JSON.stringify(e.searchTerms)},`,
      '  },',
    ].join('\n')
  ),
  '];',
  '',
  'export function getCatalogEntry(slug: string): PerfumeCatalogEntry | undefined {',
  '  return fragranceCatalog.find((e) => e.slug === slug);',
  '}',
  '',
];

writeFileSync(outPath, lines_out.join('\n'), 'utf-8');
console.log(`✓ Generated ${entries.length} entries → lib/fragrance-catalog.ts`);
